"use client";

import React, { useState, useEffect } from 'react';
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import {
    History,
    Download,
    FileText,
    Calendar,
    Clock,
    Trash2
} from "lucide-react";
import { format } from 'date-fns';
import {
    deleteReportHistory,
    getReportHistory,
    type ReportHistoryEntry,
} from "@/server/actions/reports-actions";

const ReportHistory = () => {
    const [reportHistory, setReportHistory] = useState<ReportHistoryEntry[]>([]);
    const [isLoading, setIsLoading] = useState(true);
    const [error, setError] = useState<string | null>(null);
    const [deletingId, setDeletingId] = useState<number | null>(null);

    const loadHistory = async () => {
        try {
            setReportHistory(await getReportHistory());
            setError(null);
        } catch (err) {
            console.error('Failed to load report history:', err);
            setError('Could not load report history.');
        } finally {
            setIsLoading(false);
        }
    };

    useEffect(() => {
        void loadHistory();
    }, []);

    const deleteReport = async (reportId: number) => {
        if (!window.confirm('Delete this report from history? You can generate it again any time.')) {
            return;
        }
        setDeletingId(reportId);
        try {
            await deleteReportHistory(reportId);
            await loadHistory();
        } catch (err) {
            console.error('Failed to delete report:', err);
            setError('Could not delete the report. Please try again.');
        } finally {
            setDeletingId(null);
        }
    };

    if (isLoading) {
        return (
            <Card>
                <CardHeader>
                    <CardTitle className="flex items-center gap-2">
                        <History className="h-5 w-5" />
                        Report History
                    </CardTitle>
                </CardHeader>
                <CardContent>
                    <div className="flex items-center justify-center py-8">
                        <div className="animate-spin rounded-full h-8 w-8 border-b-2 border-blue-600"></div>
                    </div>
                </CardContent>
            </Card>
        );
    }

    return (
        <div className="space-y-6">
            <Card>
                <CardHeader>
                    <div className="flex items-center justify-between">
                        <div>
                            <CardTitle className="flex items-center gap-2">
                                <History className="h-5 w-5" />
                                Report History
                            </CardTitle>
                            <CardDescription>
                                View and manage your previously generated reports
                            </CardDescription>
                        </div>
                        <Badge variant="outline" className="text-sm">
                            {reportHistory.length} reports
                        </Badge>
                    </div>
                </CardHeader>
                <CardContent>
                    {error && (
                        <p role="alert" className="text-sm text-red-600 mb-4">{error}</p>
                    )}
                    {reportHistory.length === 0 ? (
                        <div className="text-center py-8">
                            <FileText className="mx-auto h-12 w-12 text-muted-foreground mb-4" />
                            <p className="text-gray-500">No reports generated yet</p>
                            <p className="text-sm text-muted-foreground">Generated reports will appear here</p>
                        </div>
                    ) : (
                        <div className="space-y-4">
                            {reportHistory.map((report) => (
                                <div key={report.id} className="border rounded-lg p-4 hover:bg-muted transition-colors">
                                    <div className="flex items-center justify-between mb-3">
                                        <div className="flex items-center space-x-3">
                                            <FileText className="h-5 w-5 text-muted-foreground" />
                                            <div>
                                                <h4 className="font-medium text-gray-900">{report.typeName}</h4>
                                                <p className="text-sm text-gray-500">
                                                    {report.generatedByName ? `Generated by ${report.generatedByName}` : 'Generated report'}
                                                </p>
                                            </div>
                                        </div>
                                    </div>

                                    <div className="grid grid-cols-2 md:grid-cols-3 gap-4 text-sm mb-4">
                                        <div className="flex items-center space-x-2">
                                            <Calendar className="h-4 w-4 text-muted-foreground" />
                                            <span className="text-muted-foreground">
                                                {format(new Date(report.dateFrom), 'MMM dd, yyyy')} — {format(new Date(report.dateTo), 'MMM dd, yyyy')}
                                            </span>
                                        </div>
                                        <div className="flex items-center space-x-2">
                                            <Clock className="h-4 w-4 text-muted-foreground" />
                                            <span className="text-muted-foreground">
                                                {format(new Date(report.generatedAt), 'MMM dd, yyyy HH:mm')}
                                            </span>
                                        </div>
                                    </div>

                                    <div className="flex items-center justify-between pt-3 border-t">
                                        <div className="text-xs text-gray-500">
                                            Report ID: {report.id}
                                        </div>
                                        <div className="flex items-center space-x-2">
                                            <Button variant="outline" size="sm" asChild>
                                                <a href={`/api/reports/download/${report.id}`} download>
                                                    <Download className="mr-1 h-3 w-3" />
                                                    Download
                                                </a>
                                            </Button>
                                            <Button
                                                variant="outline"
                                                size="sm"
                                                onClick={() => void deleteReport(report.id)}
                                                disabled={deletingId === report.id}
                                                className="text-red-600 hover:text-red-700"
                                            >
                                                <Trash2 className="h-3 w-3" />
                                            </Button>
                                        </div>
                                    </div>
                                </div>
                            ))}
                        </div>
                    )}
                </CardContent>
            </Card>
        </div>
    );
};

export default ReportHistory;
